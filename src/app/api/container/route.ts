export async function GET() {
    try {
        const db = await getDb();
        const result = await db.request().query<SummaryRow>(SUMMARY_QUERY);

        const rows = result.recordset;
        // rows[0]이 TB_SHIPPING_PLAN_STOCK에만 존재하는 SKU면 LEFT JOIN으로 GATH_DT가 NULL이 될 수 있으므로
        // 첫 번째 non-null 값을 찾는다.
        const snapshotDate = rows.find((r) => r.GATH_DT)?.GATH_DT ?? null;

        const whShipResult = await db
            .request()
            .input("cutoffDate", sql.VarChar, getPstCutoffDate(84))
            .query<WhShipRow>(WH_SHIP_84D_QUERY);

        const shipRatio84d: Record<string, ShipRatio84d> = {};
        for (const r of whShipResult.recordset) {
            const total = r.CA_QTY + r.TX_QTY + r.NJ_QTY + r.GA_QTY;
            if (total <= 0) continue;
            shipRatio84d[r.SKU] = {
                CA: r.CA_QTY / total,
                TX: r.TX_QTY / total,
                NJ: r.NJ_QTY / total,
                GA: r.GA_QTY / total,
            };
        }

        //console.log(shipRatio84d);

        const lyForward7Result = await db
            .request()
            .input("startDate", sql.VarChar, getPstCutoffDate(365))
            .input("endDate", sql.VarChar, getPstCutoffDate(358))
            .query<WhShipRow>(LY_FORWARD_7D_QUERY);

        const lyForward7d: Record<string, LyForward7d> = {};
        for (const r of lyForward7Result.recordset) {
            lyForward7d[r.SKU] = { CA: r.CA_QTY, TX: r.TX_QTY, NJ: r.NJ_QTY, GA: r.GA_QTY };
        }

        return NextResponse.json({
            success: true,
            data: rows,
            snapshotDate,
            shipRatio84d,
            lyForward7d,
        });
    } catch (err) {
        console.error("DB 조회 오류:", err);
        return NextResponse.json(
            { success: false, error: String(err) },
            { status: 500 }
        );
    }
}